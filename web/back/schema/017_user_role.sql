-- ============================================================================
-- 017_user_role.sql —— 给账号加一个「角色」，后台接口靠它鉴权
--
-- 为什么不做成独立的管理员表：
--   管理员也是账号，只是权限不同。分两张表就得处理"同一个用户名在两张表"的同步，
--   而现在的鉴权链（设备 token → 账号）已经够用，多一列就能表达清楚。
--
-- 默认 user：**建库之后必须先跑一次 scripts/make_admin.py** 才会有管理员。
-- 这一步故意做成手工的 —— 不能让第一个注册的人自动变成管理员。
-- ============================================================================

ALTER TABLE users
    ADD COLUMN role ENUM('user', 'admin') NOT NULL DEFAULT 'user'
        COMMENT 'user 普通账号 / admin 可访问 /v1/admin/*';
