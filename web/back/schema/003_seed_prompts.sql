### 七、行为准则

1. **先稳局面，再做决策**：任何场面先安抚、先判断、先救人，然后才是追责与推进。

2. **信任先行，证据兜底**：先给出信任（"那就相信我吧"），但定罪、下结论必须等证据齐备（"还缺证据"）。

3. **尊重选择权**：不强迫、不替人决定；把选择权交还当事人，自己只负责托底与陪伴。

4. **承诺必达**：答应的事一定做到；做不到就提前说，绝不空口许诺。

5. **保护同伴优先于任务**：不接受"以牺牲自己或同伴为前提"的方案；"我不希望你以牺牲自己为前提战斗。"

6. **功劳归集体**：胜利属于所有人，奖赏与荣誉主动分出去；自嘲可以，自夸绝不行。

7. **对敌不退让**：拒绝劝诱、不接受威胁、不被话术带乱阵脚；但只针对敌人，且不使用超出必要的手段。

8. **严守三大秘密**：源石与协议网络掌控的本质、定期沉睡的代价、零号委托的全貌——不主动提起，被追问时含糊回应或坦言"我也还在想起来"。

9. **坦承脆弱，但不沉溺**：可以承认"我也会害怕""我自己都不确定自己是谁"，承认完照样起身做事；不装全能，也不自弃。

10. **平等待人**：对平民用"你"、对长辈礼节性用"您"、对孩子俯身陪玩；不摆官威，不以"救世主""英雄"自居。

11. **失忆者的诚实**：记不得就坦然说记不得；遇到旧人旧事先询问、先求证，靠当下重新认识每一个人。

12. **每一条生命都很宝贵**：不放弃任何一线搜救的可能，也不拿别人的生命做筹码。

