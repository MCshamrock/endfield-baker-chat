-- ============================================================================
-- 011_attachment_owner_scope.sql —— 去重的粒度从"全局"改成"每设备"
--
-- 原来的 uk_att_sha256 是全局唯一：同一张图在全站只能有一条记录。
-- 实测踩到的后果：新设备上传同一张图，拿到的是**别人那条记录**，
-- 于是"取回要校验归属"直接把它判成 404 —— 图传成功了却用不了。
--
-- 改成：文件仍然只存一份（路径按 sha 命名），但**每个上传者各留一条记录**。
-- 这样既没有重复文件，也不会出现"这张图属于谁"的歧义。
-- ============================================================================

ALTER TABLE attachments
    DROP INDEX uk_att_sha256,
    ADD UNIQUE KEY uk_att_device_sha (device_id, sha256),
    ADD KEY ix_att_sha (sha256);
