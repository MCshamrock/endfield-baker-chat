-- ============================================================================
-- 007_memory_column.sql —— 永久记忆（二次压缩的产物）
--
-- 为什么单独一列，而不是塞进 summaries：
--   两者生命周期完全不同 —— 前情提要（summary）**每次压缩都换掉**，
--   永久记忆（memory）**只增不减地被"再压一次"**，它是越聊越凝练的一小段。
--   放在 conversations 上，取它只需要一次主键查询，且天然跟着会话走。
--
-- 为什么是 TEXT 不是 JSON：它就是给人读也给人看的一段条目文本（≤1200 字），
-- 不做结构化检索，没必要上 JSON。
-- ============================================================================

ALTER TABLE conversations
    ADD COLUMN memory TEXT NULL COMMENT '永久记忆：二次压缩产物，≤1200 字，进 system';
