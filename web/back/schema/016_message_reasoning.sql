-- ============================================================================
-- 016_message_reasoning.sql —— 把上游的「思考过程」存下来
--
-- 项目书（docs/08 §1.3）的要求：THINK 不对用户开放，只作为服务器的存储用。
-- 所以这一列**永远不进任何下发接口**：MessageOut 不读它、SSE 不吐它、
-- 拼提示词也不带它（历史只用 text）。它只给后台/排障看。
--
-- 为什么单独一列而不是塞进 text：思考链混进正文会污染历史，
-- 而且下一次压缩会把它当剧情压进摘要里 —— 那就再也洗不掉了。
-- ============================================================================

ALTER TABLE messages
    ADD COLUMN reasoning MEDIUMTEXT NULL
        COMMENT '上游思考过程（reasoning_content），只存服务端，不下发';
