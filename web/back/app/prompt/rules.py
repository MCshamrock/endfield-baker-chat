# 「继续说」——玩家不想打字，让她接着上一条往下说。
#
# 写成一段**用户消息**（不是 system），因为 OpenAI 兼容端点对"最后一条是 system"
# 支持不一，而 user 消息在哪儿都收。内容是 OOC 指令，所以用【系统指令】框起来，
# 免得模型当成玩家在说话。
#
# 第 3 条是最容易被忽略的一条：上一条往往**已经把话说完了**，
# 这时候"接着说"应该推镜头（她做了什么、看向哪里），而不是复读或强行续台词。
CONTINUE_RULE = """【系统指令】玩家点了「继续说」，不是玩家在说话。

接着你上一条消息往下写，遵守四条：
1. 不要重复已经说过的内容，不要总结，不要重新打招呼，不要换话题。
2. 如果上一条是话说一半停下的，就从中断的那句接着说完。
3. 如果上一条已经说完了，就把镜头往前推一点：她做了个什么动作、看向哪里、又补了一句什么。
4. 篇幅和语气跟刚才一致，大约 150~300 字。"""

