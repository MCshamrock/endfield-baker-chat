// 图标取自设计稿(48×48 线框,stroke-width 4),颜色一律 currentColor:
// CSS 决定选中/未选中颜色,不写死设计稿里的 #333(深色面板上会看不见)。
//
// 一个图标由若干「路径片段」组成,而不是一整段 SVG 字符串:
//   - filled 为 true 的片段是实心点(如「!」「i」的圆点)→ currentColor 填充、不描边
//   - 其余片段一律描边、不填充(描边参数统一由组件给:width 4 / round / round)
// 之所以拆成片段而不是 v-html 整段贴:实心点与描边线在同一个图标里混用,
// 必须分别控制 fill / stroke,拼字符串会让这段逻辑散落在模板里。
// =============================================================================

